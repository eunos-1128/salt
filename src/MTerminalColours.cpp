uint8_t LookupColor(MColor color)
{
	uint8_t result = 0;

	float cr = color.red, cg = color.green, cb = color.blue;
	auto distance = std::numeric_limits<float>::max();

	for (uint8_t ix = 0; auto c : k256AnsiColors)
	{
		auto d =
			(cr - c.red) * (cr - c.red) +
			(cg - c.green) * (cg - c.green) +
			(cb - c.blue) * (cb - c.blue);

		if (distance > d)
		{
			result = ix;
			distance = d;
		}

		++ix;
	}

	return result;
}
